// docs-snippets.test.js — Static checks on the framework code snippets in README, docs and demo.

import assert from "node:assert/strict";
import { readdir, readFile } from "node:fs/promises";
import { describe, test } from "node:test";

/** The repository root: the package README is packages/core/README.md, docs/ and apps/demo/ are at the top. */
const root = new URL("../../../", import.meta.url);

/** Fenced code languages that are always framework code. */
const frameworkLanguages = new Set(["tsx", "jsx", "vue", "svelte"]);

/** Content that marks a fenced block of another language (ts, js) as framework code. */
const frameworkMarker = /sparkline-mini-charts\/(?:react|vue|angular)|@angular\/core|<script setup/;

/**
 * Reads a repository file as UTF-8 text.
 *
 * @param {string} path Path relative to the repository root.
 * @returns {Promise<string>}
 */
function readText(path) {
  return readFile(new URL(path, root), "utf8");
}

/**
 * Lists the package README.md and every Markdown file under docs/.
 *
 * @returns {Promise<string[]>} Paths relative to the repository root.
 */
async function markdownFiles() {
  const entries = await readdir(new URL("docs/", root), { recursive: true });
  const docs = entries.filter((entry) => entry.endsWith(".md")).map((entry) => `docs/${entry}`);
  return ["packages/core/README.md", ...docs.sort()];
}

/**
 * Extracts the framework code blocks from a Markdown document.
 *
 * @param {string} markdown Markdown source.
 * @returns {{ lang: string, code: string }[]}
 */
function frameworkBlocks(markdown) {
  const blocks = [];
  for (const match of markdown.matchAll(/^```(\w*)[^\n]*\n([\s\S]*?)^```/gm)) {
    const lang = match[1].toLowerCase();
    const code = match[2];
    if (frameworkLanguages.has(lang) || frameworkMarker.test(code)) blocks.push({ lang, code });
  }
  return blocks;
}

/**
 * Lists the demo's framework snippets: the Frameworks page guides and the configurator's
 * export of every chart (with a flag, a string and an object option), generated by
 * apps/demo/src/snippets.js, which has no DOM dependency.
 *
 * @returns {Promise<{ where: string, framework: string, code: string }[]>}
 */
async function demoSnippets() {
  // Non-literal specifiers: the demo modules are plain JavaScript outside this package's type check.
  const { EXPORTS, FRAMEWORK_GUIDES } = await import(new URL("apps/demo/src/snippets.js", root).href);
  const { CHARTS } = await import(new URL("apps/demo/src/catalog.js", root).href);
  const snippets = [];
  for (const guide of FRAMEWORK_GUIDES) {
    for (const file of guide.files) snippets.push({ where: `Frameworks page ${guide.id} ${file.name}`, framework: guide.id, code: file.code });
  }
  for (const chart of CHARTS) {
    const config = {
      tag: chart.tag,
      data: chart.datasets[0].data,
      label: chart.label,
      options: [
        { name: "interactive", value: true, type: "boolean", property: true },
        { name: "curve", value: "smooth", type: "enum", property: true },
        { name: "zones", value: [{ upTo: 50, color: "#10b981" }], type: "json", property: true },
      ],
    };
    for (const format of EXPORTS) snippets.push({ where: `configurator ${format.id} <${chart.tag}>`, framework: format.id, code: format.generate(config) });
  }
  return snippets;
}

describe("framework snippets bind data as a property", () => {
  test("README and docs framework blocks never JSON.stringify", async () => {
    let checked = 0;
    for (const path of await markdownFiles()) {
      for (const block of frameworkBlocks(await readText(path))) {
        checked++;
        assert.ok(!block.code.includes("JSON.stringify("), `${path} (${block.lang || "code"} block):\n${block.code}`);
      }
    }
    // React, Vue, Angular and Svelte in both README.md and docs/getting-started.md.
    assert.ok(checked >= 8, `expected at least 8 framework blocks, found ${checked}`);
  });

  test("demo snippets never JSON.stringify", async () => {
    const snippets = await demoSnippets();
    // 5 guides, plus 6 export formats for each of the 24 charts.
    assert.ok(snippets.length >= 5 + 24 * 6, `expected at least 149 snippets, found ${snippets.length}`);
    for (const { where, code } of snippets) {
      assert.ok(!code.includes("JSON.stringify("), `apps/demo ${where}:\n${code}`);
    }
  });
});

describe("framework snippets are valid for their framework", () => {
  test("JSX snippets use JSX comments, not HTML comments", async () => {
    const jsx = [];
    for (const path of await markdownFiles()) {
      for (const block of frameworkBlocks(await readText(path))) {
        if (block.lang === "tsx" || block.lang === "jsx") jsx.push({ where: path, code: block.code });
      }
    }
    for (const { where, framework, code } of await demoSnippets()) {
      if (framework === "react") jsx.push({ where: `apps/demo ${where}`, code });
    }
    assert.ok(jsx.length > 0);
    for (const { where, code } of jsx) {
      assert.ok(!code.includes("<!--"), `${where}:\n${code}`);
    }
  });

  test("Angular snippets in the demo use the AOT-safe recipe", async () => {
    const angular = (await demoSnippets()).filter((snippet) => snippet.framework === "angular").map((snippet) => snippet.code);
    // The Frameworks page guide and the configurator export of the 24 charts.
    assert.equal(angular.length, 1 + 24);
    for (const code of angular) {
      assert.match(code, /sparkline-mini-charts\/register/);
      assert.match(code, /CUSTOM_ELEMENTS_SCHEMA/);
      assert.doesNotMatch(code, /sparkline-mini-charts\/angular/, code);
    }
  });
});
